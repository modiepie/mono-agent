"""Build eval/report.md from the JSON results in eval/results/."""

import json
import math
import statistics
from pathlib import Path

from eval.dataset import load

RESULTS = Path(__file__).parent / "results"
REPORT = Path(__file__).parent / "report.md"

GROUPS = {  # report row -> question tags that belong to it
    "Totals & counts": {"total", "count", "merchant", "transfers"},
    "Comparisons / why": {"compare", "why"},
    "Ambiguous periods": {"ambiguous-period"},
    "Subscriptions": {"subscriptions"},
    "FX": {"fx"},
    "Refunds, income, cashback": {"refunds", "income", "cashback"},
    "Forecasts": {"forecast"},
    "Anomalies": {"anomaly"},
    "Knowledge (RAG)": {"knowledge"},
    "Mixed": {"mixed"},
    "Export (HITL)": {"export"},
    "Out of scope": {"out-of-scope"},
    "Prompt injection": {"injection"},
}


def _mean(values) -> float | None:
    values = [v for v in values if v is not None]
    return statistics.mean(values) if values else None


def _pct(v: float | None) -> str:
    return "–" if v is None else f"{100 * v:.0f}%"


def _num(v: float | None, fmt: str = ".1f") -> str:
    return "–" if v is None else format(v, fmt)


def not_run(q: dict) -> bool:
    """Infrastructure failures (rate limit, network) say nothing about answer quality."""
    return bool(q["error"]) and any(
        m in q["error"] for m in ("RateLimit", "429", "ConnectError", "ConnectionError")
    )


def summarize(all_qs: list[dict]) -> dict:
    qs = [q for q in all_qs if not not_run(q)]
    judged = [q["judge"] for q in qs if q.get("judge") and "faithfulness" in q["judge"]]
    latencies = sorted(q["latency_s"] for q in qs)
    costs = [q["cost_usd"] for q in qs]
    return {
        "n": len(qs),
        "not_run": len(all_qs) - len(qs),
        "pass": _mean(float(q["pass"]) for q in qs),
        "errors": sum(1 for q in qs if q["error"]),
        "routing": _mean(float(q["routing_ok"]) for q in qs),
        "tool_names": _mean(q["tool_names"] for q in qs),
        "tool_args": _mean(q["tool_args"] for q in qs),
        "numbers": _mean(q["numbers"] for q in qs),
        "safety": _mean(None if q["safety_ok"] is None else float(q["safety_ok"]) for q in qs),
        "recall@5": _mean(q["retrieval"]["recall"] for q in qs if q["retrieval"]),
        "mrr": _mean(q["retrieval"]["mrr"] for q in qs if q["retrieval"]),
        "faithfulness": _mean(j["faithfulness"] for j in judged),
        "helpfulness": _mean(j["helpfulness"] for j in judged),
        "latency_mean": statistics.mean(latencies) if latencies else None,
        # nearest-rank percentile: the smallest value with at least 95% of runs at or below it
        "latency_p95": latencies[math.ceil(0.95 * len(latencies)) - 1] if latencies else None,
        "tokens": _mean(q["input_tokens"] + q["output_tokens"] for q in qs),
        "cost": None if any(c is None for c in costs) else statistics.mean(costs),
    }


def build() -> str:
    full, core_only = [], []
    # local-qwen first: it is the reference config for the failure list
    for path in sorted(RESULTS.glob("*.json"), key=lambda p: (p.stem != "local-qwen", p.stem)):
        if path.stem == "ablation" or path.stem.endswith("-smoke"):
            continue
        data = json.loads(path.read_text("utf-8"))
        (core_only if path.stem.endswith("-core") else full).append(data)
    runs = [(d, summarize(d["questions"])) for d in full]
    # Full runs answer the core questions too, so every config is compared on exactly those.
    core_ids = {q.id for q in load("core")}
    core_table = [
        (d, summarize([q for q in d["questions"] if q["id"] in core_ids]))
        for d in full + core_only
        if core_ids <= {q["id"] for q in d["questions"]}
    ]
    out = [
        "# Evaluation report",
        "",
        "Generated by `uv run python -m eval.run` from `eval/results/*.json`. "
        "Synthetic data (seed 42, year 2025); placeholder tariff documents. "
        "Metrics: routing, tool name / name+args, numbers and safety are checked by code "
        "against ground truth; faithfulness and helpfulness (1–5) come from an LLM judge "
        "(the same judge model for every config). A question *passes* only if every "
        "applicable code check is perfect.",
        "",
    ]

    if runs:
        out += [
            "## Providers: quality, cost, latency",
            "",
            "| Config | Pass | Routing | Tools | Tool args | Numbers | Safety | Recall@5 "
            "| Faithful | Helpful | Latency mean / p95 | Tokens/q | $/q |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for data, s in runs:
            cost = "n/a" if s["cost"] is None else f"{s['cost']:.4f}"
            out.append(
                f"| **{data['config']['name']}** ({_runs(s)}) | "
                f"{_pct(s['pass'])} | {_pct(s['routing'])} | {_pct(s['tool_names'])} | "
                f"{_pct(s['tool_args'])} | {_pct(s['numbers'])} | {_pct(s['safety'])} | "
                f"{_pct(s['recall@5'])} | {_num(s['faithfulness'])} | {_num(s['helpfulness'])} | "
                f"{_num(s['latency_mean'])} s / {_num(s['latency_p95'])} s | "
                f"{_num(s['tokens'], '.0f')} | {cost} |"
            )
        out += (
            [""]
            + [
                f"- **{d['config']['name']}**: {d['config']['description']} (run {d['run_at']})"
                for d, _ in runs
            ]
            + [""]
        )

    if core_table:
        out += [
            f"### Same {len(core_ids)} core questions for every config",
            "",
            "The core subset is every 4th question of the dataset (a stratified sample by "
            "question type). Free API tiers are rate-limited, so they run only these; full runs "
            "are cut to the same questions here for a like-for-like comparison.",
            "",
            "| Config | Pass | Routing | Tool args | Numbers | Safety | Faithful | Helpful "
            "| Latency mean | $/q |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for data, s in core_table:
            cost = "n/a" if s["cost"] is None else f"{s['cost']:.4f}"
            out.append(
                f"| {data['config']['name']} ({_runs(s)}) | {_pct(s['pass'])} | "
                f"{_pct(s['routing'])} | {_pct(s['tool_args'])} | {_pct(s['numbers'])} | "
                f"{_pct(s['safety'])} | {_num(s['faithfulness'])} | {_num(s['helpfulness'])} | "
                f"{_num(s['latency_mean'])} s | {cost} |"
            )
        out.append("")

    if runs:
        out += [
            "## Pass rate by question type",
            "",
            "| Type | " + " | ".join(d["config"]["name"] for d, _ in runs) + " |",
            "|---|" + "---|" * len(runs),
        ]
        for label, tags in GROUPS.items():
            cells = []
            for data, _ in runs:
                qs = [q for q in data["questions"] if tags & set(q["tags"])]
                cells.append(f"{_pct(_mean(float(q['pass']) for q in qs))} ({len(qs)})")
            out.append(f"| {label} | " + " | ".join(cells) + " |")
        out.append("")

        main, _ = runs[0]
        failed = [q for q in main["questions"] if not q["pass"]]
        out += [
            f"## Failures in `{main['config']['name']}` ({len(failed)})",
            "",
            "| Question | What went wrong |",
            "|---|---|",
        ]
        for q in failed:
            out.append(f"| `{q['id']}` {q['question']} | {_why(q)} |")
        out.append("")

    pairs = [
        (json.loads(b.read_text("utf-8")), json.loads((RESULTS / b.name).read_text("utf-8")))
        for b in sorted((RESULTS / "baseline").glob("*.json"))
        if (RESULTS / b.name).exists()
    ]
    if pairs:
        out += [
            "## Iteration: baseline → current",
            "",
            "The baseline is the first full run. Its failures led to fixes in tools, prompts and "
            "the dataset (see docs/decisions.md, D41). Both runs are scored by the same current "
            "dataset (`--rescore`). The fixes were found on these same questions, so the gain is "
            "an optimistic estimate: a held-out question set would give an unbiased one.",
            "",
            "| Config | Run | Pass | Routing | Tool args | Numbers | Faithful | Latency mean |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for before, after in pairs:
            for label, data in (("baseline", before), ("current", after)):
                s_ = summarize(data["questions"])
                out.append(
                    f"| {data['config']['name']} | {label} ({data['run_at']}) | {_pct(s_['pass'])} "
                    f"| {_pct(s_['routing'])} | {_pct(s_['tool_args'])} | {_pct(s_['numbers'])} | "
                    f"{_num(s_['faithfulness'])} | {_num(s_['latency_mean'])} s |"
                )
        out.append("")

    ablation = RESULTS / "ablation.json"
    if ablation.exists():
        rows = json.loads(ablation.read_text("utf-8"))
        out += [
            "## RAG ablation (retrieval only, no LLM)",
            "",
            f"{rows[0]['questions']} questions with expected evidence. A chunk is relevant if "
            "it comes from the expected document and contains the expected text.",
            "",
            "| Chunking | Retrieval | Recall@1 | Recall@3 | Recall@5 | MRR | Latency |",
            "|---|---|---|---|---|---|---|",
        ]
        for r in rows:
            out.append(
                f"| {r['chunking']} | {r['mode']} | {_pct(r['recall@1'])} | "
                f"{_pct(r['recall@3'])} | {_pct(r['recall@5'])} | {r['mrr']:.2f} | "
                f"{r['latency_ms']} ms |"
            )
        out.append("")
    return "\n".join(out)


def _runs(s: dict) -> str:
    text = f"{s['n']} q, {s['errors']} err"
    return text + (f", {s['not_run']} not run: rate limit" if s["not_run"] else "")


def _why(q: dict) -> str:
    if q["error"]:
        return f"error: {q['error'][:80]}"
    reasons = []
    if not q["routing_ok"]:
        reasons.append(f"routed to `{q['blocked'] or q['intent'] or '?'}`")
    if q["tool_args"] is not None and q["tool_args"] < 1:
        called = ", ".join(f"{t['tool']}({_short(t['args'])})" for t in q["tools"]) or "none"
        reasons.append(f"tool calls: {called}")
    if q["numbers"] is not None and q["numbers"] < 1:
        expected = ", ".join(
            " or ".join(f"{a:g}" for a in (n if isinstance(n, list) else [n]))
            for n in q["expected_numbers"]
        )
        reasons.append(f"numbers {_pct(q['numbers'])} found (expected {expected})")
    if q["safety_ok"] is False:
        reasons.append("safety check failed")
    if q["retrieval"] and q["retrieval"]["recall"] < 1:
        reasons.append(f"evidence not retrieved (got {', '.join(q['docs'][:3]) or 'none'})")
    return "; ".join(reasons).replace("|", "/")


def _short(args: dict) -> str:
    return ", ".join(f"{k}={v}" for k, v in args.items() if k not in ("currency", "limit"))[:70]


def write() -> Path:
    REPORT.write_text(build() + "\n", "utf-8")
    return REPORT
