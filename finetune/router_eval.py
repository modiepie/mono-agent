"""Router: QLoRA-tuned small models vs prompting, on the eval questions (never trained on).

    uv run --group finetune python -m finetune.router_eval     # -> results.json, report.md

Setups: the same small base models with the production router prompt, the same models with a
QLoRA adapter and a one-line prompt, and the production router (big models via Ollama with
structured output). Only routing is measured: intent accuracy and latency per call.
"""
# pyright: reportMissingImports=false
# (mlx is macOS-only and lives in the optional `finetune` group; CI runs on Linux)

import json
import re
import statistics
import time
from collections.abc import Callable
from pathlib import Path
from typing import cast

from langchain_core.messages import HumanMessage, SystemMessage

from eval.dataset import Question, load
from finetune.router_data import INTENTS, SYSTEM
from mono_agent.graph.prompts import ROUTER
from mono_agent.graph.state import RouterDecision
from mono_agent.providers import chat_model

HERE = Path(__file__).parent
TODAY = "2025-12-31"  # the eval's synthetic "today"
PROMPTED = (
    ROUTER.format(today=TODAY)
    + "\nReply with the intent only: transactions, knowledge, mixed, export or out_of_scope."
)
SMALL = {
    "qwen3-0.6b": "mlx-community/Qwen3-0.6B-4bit",
    "qwen3-1.7b": "mlx-community/Qwen3-1.7B-4bit",
}
BIG = {
    "Qwen3.6 35B-A3B (production router)": "ollama:qwen3.6:35b-a3b-q4_K_M",
    "Gemma 4 (router in local-mixed)": "ollama:gemma4:latest",
}

Classify = Callable[[str], str]


def questions() -> list[Question]:
    # Pure injections are blocked by the guardrail in code and never reach the router.
    return [q for q in load() if q.intents != ["injection"]]


def parse(text: str) -> str:
    """The first intent label in the output ("out of scope" counts), else "invalid"."""
    found = [
        (m.start(), label)
        for label in INTENTS
        if (m := re.search(label.replace("_", "[_ ]"), text.lower()))
    ]
    return min(found)[1] if found else "invalid"


def mlx_classifier(model_id: str, adapter: Path | None, system: str) -> Classify:
    from mlx_lm import generate
    from mlx_lm import load as load_model

    model, tokenizer = load_model(model_id, adapter_path=str(adapter) if adapter else None)[:2]

    def classify(question: str) -> str:
        messages = [{"role": "system", "content": system}, {"role": "user", "content": question}]
        prompt = tokenizer.apply_chat_template(
            messages, tokenize=False, add_generation_prompt=True, enable_thinking=False
        )
        return parse(generate(model, tokenizer, prompt, max_tokens=8))

    return classify


def production_classifier(spec: str) -> Classify:
    llm = chat_model(spec).with_structured_output(RouterDecision)
    system = SystemMessage(ROUTER.format(today=TODAY))

    def classify(question: str) -> str:
        return cast(RouterDecision, llm.invoke([system, HumanMessage(question)])).intent

    return classify


def run(name: str, classify: Classify, qs: list[Question]) -> dict:
    classify(qs[0].q)  # warm-up: model load / graph compilation is not per-call latency
    rows = []
    for q in qs:
        start = time.perf_counter()
        intent = classify(q.q)
        rows.append(
            {
                "id": q.id,
                "expected": q.intents,
                "intent": intent,
                "ok": intent in q.intents,
                "latency_s": round(time.perf_counter() - start, 3),
            }
        )
    latencies = [r["latency_s"] for r in rows]
    summary = {
        "setup": name,
        "accuracy": round(sum(r["ok"] for r in rows) / len(rows), 3),
        "invalid": sum(r["intent"] == "invalid" for r in rows),
        "median_latency_s": round(statistics.median(latencies), 3),
        "p95_latency_s": round(statistics.quantiles(latencies, n=20)[-1], 3),
        "questions": rows,
    }
    print(f"{name}: {summary['accuracy']:.0%}, median {summary['median_latency_s']} s", flush=True)
    return summary


def report(results: list[dict]) -> str:
    n = len(results[0]["questions"])
    lines = [
        "# Router: QLoRA vs prompting",
        "",
        f"Generated by `finetune/router_eval.py`. {n} eval questions (every routable question of "
        "the 77; never used for training). Latency is one routing call on an M1 Max: MLX for "
        "the small models, Ollama for the big ones.",
        "",
        "| Setup | Accuracy | Invalid output | Median latency | p95 latency |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        lines.append(
            f"| {r['setup']} | {r['accuracy']:.0%} | {r['invalid']} | "
            f"{r['median_latency_s'] * 1000:.0f} ms | {r['p95_latency_s'] * 1000:.0f} ms |"
        )
    lines += ["", "## Misrouted questions", ""]
    for r in results:
        misses = [q for q in r["questions"] if not q["ok"]]
        if misses:
            items = ", ".join(f"`{q['id']}` → {q['intent']}" for q in misses)
            lines.append(f"- **{r['setup']}** ({len(misses)}): {items}")
    return "\n".join(lines) + "\n"


def main() -> None:
    qs = questions()
    results = []
    for short, model_id in SMALL.items():
        results.append(run(f"{short} prompted", mlx_classifier(model_id, None, PROMPTED), qs))
        adapter = HERE / "adapters" / short
        if (adapter / "adapters.safetensors").exists():
            results.append(run(f"{short} + QLoRA", mlx_classifier(model_id, adapter, SYSTEM), qs))
        else:
            print(f"no adapter for {short}: train it first (finetune/lora.yaml)")
    for name, spec in BIG.items():
        results.append(run(name, production_classifier(spec), qs))
    (HERE / "results.json").write_text(json.dumps(results, ensure_ascii=False, indent=1))
    (HERE / "report.md").write_text(report(results))


if __name__ == "__main__":
    main()
